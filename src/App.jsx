// ── Строим все шаги для группы ──
function buildSteps(group, axisUsed){
  const steps=[];
  const n=group.length;
  if(n<2) return steps;
  const qt=questionType(n);

  if(qt==="pair"){
    const ax=Math.max(axisUsed[group[0]]||0, axisUsed[group[1]]||0);
    steps.push({type:"pair",talents:group.slice(),axisLevel:ax});
  } else if(qt==="rank"){
    const ax=Math.max(...group.map(t=>axisUsed[t]||0));
    steps.push({type:"rank",talents:group.slice(),axisLevel:ax});
  } else if(qt==="pairs"){
    makePairs(group).forEach(([a,b])=>{
      const ax=Math.max(axisUsed[a]||0,axisUsed[b]||0);
      steps.push({type:"pair",talents:[a,b],axisLevel:ax});
    });
  } else {
    // 6+ → группы
    const groups=splitIntoGroups(group);
    // Шаг 1: каждая группа
    groups.forEach((g,gi)=>{
      const ax=Math.max(...g.map(t=>axisUsed[t]||0));
      steps.push({type:"rank",talents:g.slice(),axisLevel:ax,groupIdx:gi,totalGroups:groups.length,sourceGroups:groups});
    });
    // После групп оси увеличиваются
    const newUsed={...axisUsed};
    group.forEach(t=>{newUsed[t]=(axisUsed[t]||0)+1;});
    // Шаг 2: финалы по местам
    const maxPlaces=Math.max(...groups.map(g=>g.length));
    let pendingSingles=[];
    for(let place=0;place<maxPlaces;place++){
      let placeGroup=groups.map(g=>g[place]).filter(Boolean);
      if(pendingSingles.length>0){
        placeGroup=[...pendingSingles,...placeGroup];
        pendingSingles=[];
      }
      if(placeGroup.length===1){pendingSingles.push(placeGroup[0]);continue;}
      if(placeGroup.length<2) continue;
      const ax2=Math.max(...placeGroup.map(t=>newUsed[t]||0));
      const qt2=questionType(placeGroup.length);
      if(qt2==="pair"){
        steps.push({type:"pair",talents:placeGroup.slice(),axisLevel:ax2,finalePlace:place});
      } else if(qt2==="rank"){
        steps.push({type:"rank",talents:placeGroup.slice(),axisLevel:ax2,finalePlace:place});
      } else if(qt2==="pairs"){
        makePairs(placeGroup).forEach(([a,b])=>{
          const ax3=Math.max(newUsed[a]||0,newUsed[b]||0);
          steps.push({type:"pair",talents:[a,b],axisLevel:ax3,finalePlace:place});
        });
      } else {
        const sub=buildSteps(placeGroup,newUsed);
        sub.forEach(s=>{s.finalePlace=place;});
        steps.push(...sub);
      }
    }
    // Одиночки добавляем к последнему финалу
    if(pendingSingles.length>0){
      const lastFinale=steps.filter(s=>s.finalePlace!==undefined).slice(-1)[0];
      if(lastFinale){
        lastFinale.talents=[...lastFinale.talents,...pendingSingles];
        const qt3=questionType(lastFinale.talents.length);
        lastFinale.type=qt3==="pair"?"pair":"rank";
      }
    }
  }
  return steps;
}

