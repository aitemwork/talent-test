function calcScores(answers) {
  const scores={}, mainHits={}, extraHits={};
  Object.keys(STATEMENTS).forEach(t=>{scores[t]=0;mainHits[t]=0;extraHits[t]=0;});
  QUESTIONS.forEach((q,i)=>{
    const c=answers[i]; if(!c) return;
    const pts=q[c]; const keys=Object.keys(pts);
    if(keys[0]&&scores[keys[0]]!==undefined){scores[keys[0]]+=pts[keys[0]];mainHits[keys[0]]++;}
    if(keys[1]&&scores[keys[1]]!==undefined){scores[keys[1]]+=pts[keys[1]];extraHits[keys[1]]++;}
  });
  return {scores,mainHits,extraHits};
}

function eqKey(t,scores,mainHits,extraHits){
  return `${scores[t]}_${mainHits[t]}_${extraHits[t]}`;
}

function primarySort(scores,mainHits,extraHits){
  return Object.keys(scores).sort((a,b)=>{
    if(scores[b]!==scores[a]) return scores[b]-scores[a];
    if(mainHits[b]!==mainHits[a]) return mainHits[b]-mainHits[a];
    return extraHits[b]-extraHits[a];
  });
}

function findTop10(sorted,scores,mainHits,extraHits){
  let confirmed=[],border=null,needed=0,i=0;
  while(i<sorted.length){
    const key=eqKey(sorted[i],scores,mainHits,extraHits);
    const group=[];
    while(i<sorted.length&&eqKey(sorted[i],scores,mainHits,extraHits)===key){group.push(sorted[i]);i++;}
    const would=confirmed.length+group.length;
    if(would<=10){confirmed=[...confirmed,...group];}
    else{border=group;needed=10-confirmed.length;break;}
    if(confirmed.length===10) break;
  }
  return {confirmed,border,needed};
}

// ── Деление на группы (только 3 и 4, из разных блоков) ──
function splitIntoGroups(talents){
  const n=talents.length;
  let sizes=[];
  if(n===6) sizes=[3,3];
  else if(n===7) sizes=[3,4];
  else if(n===8) sizes=[4,4];
  else if(n===9) sizes=[3,3,3];
  else if(n===10) sizes=[3,3,4];
  else if(n===11) sizes=[3,4,4];
  else if(n===12) sizes=[4,4,4];
  else{
    let rem=n;
    while(rem>0){
      if(rem<=4){sizes.push(rem);rem=0;}
      else{sizes.push(4);rem-=4;}
    }
  }
  // Распределяем из разных блоков змейкой
  const byBlock={};
  talents.forEach(t=>{const b=getBlock(t);if(!byBlock[b])byBlock[b]=[];byBlock[b].push(t);});
  const blockArrays=Object.values(byBlock);
  const allSorted=[];
  const maxLen=Math.max(...blockArrays.map(a=>a.length));
  for(let row=0;row<maxLen;row++)
    for(let col=0;col<blockArrays.length;col++)
      if(row<blockArrays[col].length) allSorted.push(blockArrays[col][row]);
  const groups=[];
  let idx=0;
  for(const size of sizes){groups.push(allSorted.slice(idx,idx+size));idx+=size;}
  return groups;
}

