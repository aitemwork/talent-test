function questionType(n){
  if(n===2) return "pair";
  if(n<=4)  return "rank";
  if(n===5) return "pairs";
  return "groups";
}

function makePairs(arr){
  const pairs=[];
  for(let i=0;i<arr.length;i++)
    for(let j=i+1;j<arr.length;j++)
      pairs.push([arr[i],arr[j]]);
  return pairs;
}

