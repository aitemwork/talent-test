function buildAllTbSteps(confirmed, border, needed, scores, mainHits, extraHits){
  const steps=[];
  const axisUsed={};
  // Группы с одинаковыми показателями внутри confirmed
  const confGroups={};
  confirmed.forEach(t=>{
    const k=eqKey(t,scores,mainHits,extraHits);
    if(!confGroups[k]) confGroups[k]=[];
    confGroups[k].push(t);
  });
  for(const group of Object.values(confGroups)){
    if(group.length<2) continue;
    const s=buildSteps(group,axisUsed);
    s.forEach(step=>{step.isConfirmed=true;});
    steps.push(...s);
    // Обновляем оси
    group.forEach(t=>{axisUsed[t]=(axisUsed[t]||0)+1;});
  }
  // Пограничная группа
  if(border&&needed<border.length){
    const s=buildSteps(border,axisUsed);
    s.forEach(step=>{step.isBorder=true;});
    steps.push(...s);
  }
  return steps;
}

