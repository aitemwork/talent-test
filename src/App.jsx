function calcGroupScores(tbSteps, tbAnswers){
  const gScores={};
  Object.keys(STATEMENTS).forEach(t=>{gScores[t]=0;});

  tbSteps.forEach((step,idx)=>{
    const ans=tbAnswers[idx];
    if(!ans) return;

    if(step.type==="pair"){
      // ans = победитель (строка)
      if(typeof ans==="string"&&gScores[ans]!==undefined){
        gScores[ans]+=0.00003;
      }
    } else if(step.type==="rank"){
      // ans = [первый, второй, третий, ...]
      if(Array.isArray(ans)){
        const bonuses=[0.00003,0.00002,0.00001,0.000005];
        // Финальный бонус меньше если это финальный шаг
        const isFinale=step.finalePlace!==undefined;
        const mult=isFinale?0.1:1;
        ans.forEach((t,i)=>{
          if(gScores[t]!==undefined){
            gScores[t]+=(bonuses[i]||0.000001)*mult;
          }
        });
      }
    }
  });
  return gScores;
}

