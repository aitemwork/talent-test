function buildRankedTop10(top10data) {
  const ranked = [];
  let place = 1, i = 0;
  while (i < top10data.length) {
    const score = top10data[i].score;
    const group = [];
    while (i < top10data.length && Math.abs(top10data[i].score - score) < 0.0000001) {
      group.push(top10data[i]); i++;
    }
    const placeStr = group.length > 1 ? `${place}–${place+group.length-1}` : `${place}`;
    ranked.push({ place: placeStr, talents: group, isTied: group.length > 1 });
    place += group.length;
  }
  return ranked;
}

