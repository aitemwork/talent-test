// Делим таланты на группы из разных блоков (по 3-4)
function splitIntoGroups(talents) {
  const byBlock = {};
  talents.forEach(t => {
    const b = getBlock(t);
    if (!byBlock[b]) byBlock[b] = [];
    byBlock[b].push(t);
  });

  // Распределяем змейкой по блокам
  const blockArrays = Object.values(byBlock);
  const size = talents.length <= 6 ? 3 : talents.length <= 9 ? 3 : 4;
  const groups = [];
  let current = [];
  let bi = 0, ii = 0;
  const allSorted = [];

  // Чередуем из разных блоков
  const maxLen = Math.max(...blockArrays.map(a=>a.length));
  for (let row=0; row<maxLen; row++) {
    for (let col=0; col<blockArrays.length; col++) {
      if (blockArrays[col][row]) allSorted.push(blockArrays[col][row]);
    }
  }

  for (const t of allSorted) {
    current.push(t);
    if (current.length === size) { groups.push([...current]); current=[]; }
  }
  if (current.length > 0) groups.push(current);

  return groups;
}

