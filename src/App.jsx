  function buildTbSteps(confirmed, border, needed, scores, mainHits, extraHits, usedAx) {
    const steps = [];

    // Вспомогательная функция — добавляем шаги для группы
    function addStepsForGroup(group, isBorder) {
      if (group.length < 2) return;

      if (group.length <= 5) {
        // 2-5 талантов → попарно
        const pairs = makePairs(group);
        pairs.forEach(([a,b]) => {
          const ax = Math.max(getAxis(a, usedAx), getAxis(b, usedAx));
          steps.push({ type:"pair", talents:[a,b], axis:ax, group, isBorder:!!isBorder });
        });
      } else {
        // 6+ талантов → делим на группы по 3 из разных блоков
        const subGroups = splitIntoGroups(group);
        subGroups.forEach(g => {
          const ax = Math.max(...g.map(t => getAxis(t, usedAx)));
          steps.push({ type:"rank", talents:g, axis:ax, group, isBorder:!!isBorder });
        });
        // Финал победителей групп
        if (subGroups.length > 1) {
          // Собираем победителей — по одному из каждой группы
          const finalists = subGroups.map(g => g[0]); // победители определятся по ответам
          const ax = Math.max(...finalists.map(t => getAxis(t, usedAx)));
          steps.push({ type:"final", talents:finalists, subGroups, axis:ax, group, isBorder:!!isBorder });
        }
      }
    }

    // 1. Группы внутри confirmed с одинаковыми показателями
    const confGroups = {};
    confirmed.forEach(t => {
      const k = eqKey(t, scores, mainHits, extraHits);
      if (!confGroups[k]) confGroups[k] = [];
      confGroups[k].push(t);
    });
    for (const group of Object.values(confGroups)) {
      addStepsForGroup(group, false);
    }

    // 2. Пограничная группа
    if (border && needed < border.length) {
      addStepsForGroup(border, true);
    }

    return steps;
  }

  // ── ДОП ВОПРОСЫ — ОТВЕТ ──
  function chooseTb(winner) {
    if (tbSelected) return;
    setTbSelected(winner);
    setTimeout(() => {
      const newA = { ...tbAnswers, [tbIdx]: winner };
      setTbAnswers(newA);
      setTbSelected(null);

      // Обновляем usedAxes
      const step = tbSteps[tbIdx];
      let newUsed = { ...usedAxes };
      step.talents.forEach(t => { newUsed = markAxisUsed(t, newUsed); });
      setUsedAxes(newUsed);

      if (tbIdx < tbSteps.length-1) { setTbIdx(i=>i+1); }
      else { buildFinal(newA, mainData); }
    }, 280);
  }

  function chooseTbRank(ranked) {
    // ranked = [first, second, third, ...]
    const newA = { ...tbAnswers, [tbIdx]: ranked };
    setTbAnswers(newA);
    const step = tbSteps[tbIdx];
    let newUsed = { ...usedAxes };
    step.talents.forEach(t => { newUsed = markAxisUsed(t, newUsed); });
    setUsedAxes(newUsed);
    if (tbIdx < tbSteps.length-1) { setTbIdx(i=>i+1); }
    else { buildFinal(newA, mainData); }
  }

