/**
 * Шаг 1: Группируем таланты по баллам
 * Возвращает группы: [ {score: 8, talents: ['Мышление','Взаимосвязанность']}, ... ]
 */
export function groupByScore(scores) {
  const sorted = Object.entries(scores).sort((a,b) => b[1]-a[1]);
  const groups = [];
  let currentGroup = null;

  for (const [talent, score] of sorted) {
    if (!currentGroup || currentGroup.score !== score) {
      currentGroup = { score, talents: [] };
      groups.push(currentGroup);
    }
    currentGroup.talents.push(talent);
  }
  return groups;
}

/**
 * Шаг 2: Определяем какие группы нужны для топ-10
 * Возвращает:
 *   confirmed   — таланты которые точно в топ-10 (полные группы)
 *   borderGroup — пограничная группа (нужна частично)
 *   needed      — сколько нужно из пограничной группы
 */
export function findTop10Groups(groups) {
  let confirmed = [];
  let borderGroup = null;
  let needed = 0;

  for (const group of groups) {
    const wouldHave = confirmed.length + group.talents.length;

    if (wouldHave <= 10) {
      // Вся группа входит
      confirmed = confirmed.concat(group.talents);
    } else {
      // Эта группа пограничная
      borderGroup = group;
      needed = 10 - confirmed.length;
      break;
    }

    if (confirmed.length === 10) break;
  }

  return { confirmed, borderGroup, needed };
}

/**
 * Шаг 3: Генерируем все пары для попарного сравнения
 */
export function generatePairs(talents) {
  const pairs = [];
  for (let i = 0; i < talents.length; i++) {
    for (let j = i+1; j < talents.length; j++) {
      pairs.push([talents[i], talents[j]]);
    }
  }
  return pairs;
}

/**
 * Шаг 4: Считаем победы по результатам попарных сравнений
 * pairResults: { 'Фокус_Планер': 'Фокус', 'Фокус_Обаяние': 'Обаяние', ... }
 * Возвращает: { 'Фокус': 1, 'Планер': 0, 'Обаяние': 1 }
 */
export function countWins(talents, pairResults) {
  const wins = {};
  for (const t of talents) wins[t] = 0;

  for (const [key, winner] of Object.entries(pairResults)) {
    if (winner && wins[winner] !== undefined) {
      wins[winner]++;
    }
  }
  return wins;
}

/**
 * Шаг 5: Сортируем таланты по победам + разрешаем ничьи через прямой матч
 * Возвращает отсортированный массив талантов
 */
export function sortByWins(talents, wins, pairResults) {
  return [...talents].sort((a, b) => {
    if (wins[b] !== wins[a]) return wins[b] - wins[a];

    // Ничья — смотрим прямой матч
    const key1 = `${a}_${b}`;
    const key2 = `${b}_${a}`;
    const direct = pairResults[key1] || pairResults[key2];
    if (direct === a) return -1;
    if (direct === b) return 1;
    return 0; // цикл — равны
  });
}

/**
 * Шаг 6: Добавляем микробаллы по результатам сравнений
 * Чтобы сохранить правильный порядок в итоговом списке
 * +0.01 за каждую победу (макс для 39 побед = +0.39 — никогда не превысит 1 балл)
 */
export function addMicroScores(talents, wins, scores) {
  const result = { ...scores };
  for (const t of talents) {
    result[t] = scores[t] + (wins[t] || 0) * 0.01;
  }
  return result;
}

/**
 * Шаг 7: Проверяем есть ли цикл среди талантов с одинаковым числом побед
 */
export function hasCycle(talents, wins, pairResults) {
  // Находим таланты с одинаковым числом побед
  const winCounts = {};
  for (const t of talents) {
    const w = wins[t];
    if (!winCounts[w]) winCounts[w] = [];
    winCounts[w].push(t);
  }

  // Проверяем цикл для каждой группы с одинаковыми победами
  for (const group of Object.values(winCounts)) {
    if (group.length < 3) continue;

    // Простая проверка цикла для 3 талантов
    if (group.length === 3) {
      const [a, b, c] = group;
      const ab = pairResults[`${a}_${b}`] || pairResults[`${b}_${a}`];
      const bc = pairResults[`${b}_${c}`] || pairResults[`${c}_${b}`];
      const ca = pairResults[`${c}_${a}`] || pairResults[`${a}_${c}`];

      if (ab === a && bc === b && ca === c) return true; // A→B→C→A
      if (ab === b && bc === c && ca === a) return true; // B→C→A→B
    }
  }
  return false;
}

